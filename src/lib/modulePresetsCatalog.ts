/**
 * Lấy danh sách các khối mẫu theo danh mục / chủ đề
 */
export function getPresetsByCategory(categoryId: string): ModulePresetItem[] {
  return MODULE_PRESETS.filter((p) => p.category === categoryId);
}

/**
 * Lấy thông tin thư mục / chủ đề theo id
 */
export function getCategoryFolder(categoryId: string): ModuleCategoryFolder | undefined {
  return MODULE_CATEGORIES.find((c) => c.id === categoryId);
}
